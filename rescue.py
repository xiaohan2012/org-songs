"""Generate a checklist of popular songs by known artists, to help recall songs missing from the org file.

For every artist section in songs.org (plus EXTRA_ARTISTS), fetch the artist's hot songs from NetEase Cloud Music,
drop songs already in songs.org and variants (live, accompaniment, remix...), and write the rest as org checkboxes.

Usage: python rescue.py [--force]  # writes rescue.org next to songs.org; --force overwrites an existing one
"""

import json
import re
import sys
import time
import urllib.parse
import urllib.request
from pathlib import Path

from orgparse import load

SONGS_ORG = Path("/Users/hanxiao/docs/notes/songs.org")
RESCUE_ORG = SONGS_ORG.with_name("rescue.org")
SONGS_PER_ARTIST = 20

# Sections of songs.org that group songs by genre or source, not by artist.
NON_ARTIST_SECTIONS = {
    "儿歌", "未归档", "魔力宝贝", "英文老歌", "吉他指弹", "放牛班的春天", "音乐之声", "音乐之声 Sound of Music",
    "合唱", "古典", "light music", "A Capella", "宝莲灯", "冰雪奇缘", "长发公主", "country music",
    "High school musical",
}

# songs.org or EXTRA_ARTISTS name -> the artist's name on NetEase, where they differ.
NETEASE_NAMES = {"飞儿乐队": "F.I.R.", "李建": "李健", "羽泉": "羽·泉", "叶倩文": "叶蒨文"}

# Artists of the same era that are absent from songs.org, to jog memory.
EXTRA_ARTISTS = [
    "张学友", "刘德华", "王杰", "齐秦", "孙燕姿", "陈奕迅", "莫文蔚", "林志炫", "伍佰", "陶喆", "S.H.E", "张惠妹",
    "光良", "动力火车", "刀郎", "许巍", "朴树", "水木年华", "小虎队", "Beyond", "张雨生", "李宗盛", "罗大佑",
    "周传雄", "王心凌", "羽泉", "老狼", "叶倩文", "林忆莲", "赵传", "姜育恒", "孟庭苇", "张宇", "萧亚轩", "张韶涵",
    "杨坤",
]

VARIANT_PATTERN = re.compile(r"live|伴奏|remix|dj|demo|instrumental|纯音乐|版|cover", re.IGNORECASE)


def get_json(url: str) -> dict:
    """Fetch `url` and parse it as JSON."""
    with urllib.request.urlopen(url, timeout=15) as response:
        return json.load(response)


def normalize(title: str) -> str:
    """Lowercase `title` without parenthesized parts and punctuation, for comparing song names."""
    title = re.sub(r"[(（\[【].*?[)）\]】]", "", title)
    return re.sub(r"[\W_]+", "", title).lower()


def find_artist_id(name: str) -> int | None:
    """Return the NetEase id of the artist called exactly `name`, or None."""
    query = urllib.parse.urlencode({"s": name, "type": 100, "limit": 5})
    artists = get_json(f"https://music.163.com/api/search/get?{query}").get("result", {}).get("artists", [])
    return next((a["id"] for a in artists if a["name"].lower() == name.lower()), None)


def hot_songs(artist_id: int) -> list[str]:
    """Return the names of the artist's hot songs, most popular first."""
    return [song["name"] for song in get_json(f"https://music.163.com/api/artist/{artist_id}").get("hotSongs", [])]


def main():
    if RESCUE_ORG.exists() and "--force" not in sys.argv:
        sys.exit(f"{RESCUE_ORG} exists; pass --force to overwrite it (your checkmarks would be lost)")

    sections = [node for node in load(SONGS_ORG).children if node.heading]
    known = {normalize(song.heading) for section in sections for song in section.children}
    artists = [s.heading for s in sections if s.heading not in NON_ARTIST_SECTIONS]
    artists += [a for a in EXTRA_ARTISTS if a not in artists]

    lines = [
        "#+title: Rescue songs",
        "Popular songs by artists in songs.org and of the same era, minus songs already there (generated by rescue.py).",
        "Tick the ones you remember, then add them in simple-mpc with =y=.",
        "",
    ]
    not_found = []
    for artist in artists:
        artist_id = find_artist_id(NETEASE_NAMES.get(artist, artist))
        time.sleep(0.3)
        if artist_id is None:
            not_found.append(artist)
            continue
        seen = set()
        candidates = []
        for name in hot_songs(artist_id):
            key = normalize(name)
            if not key or key in known or key in seen or VARIANT_PATTERN.search(name):
                continue
            seen.add(key)
            candidates.append(name)
        time.sleep(0.3)
        lines.append(f"* {artist} [/]")
        lines += [f"- [ ] {name}" for name in candidates[:SONGS_PER_ARTIST]]
        print(f"{artist}: {min(len(candidates), SONGS_PER_ARTIST)} songs")

    RESCUE_ORG.write_text("\n".join(lines) + "\n")
    print(f"wrote {RESCUE_ORG}")
    if not_found:
        print(f"artists not found on NetEase: {', '.join(not_found)}")


if __name__ == "__main__":
    main()
