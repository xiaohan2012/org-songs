"""Pick a YouTube video for every ticked song in rescue.org, for review, then add the reviewed songs to songs.org.

Usage:
    python rescue_pick.py          # writes rescue-review.org: one entry per ticked song with the best video found
    python rescue_pick.py --apply  # appends the entries of rescue-review.org to songs.org (skipping ones already there)

Review rescue-review.org between the two steps: replace wrong URLs, delete entries you don't want.
Re-running the first step appends only newly ticked songs, keeping your review edits; untick songs you delete, or they come back.
Then `python main.py` downloads them.
"""

import re
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

from orgparse import load

from rescue import RESCUE_ORG, SONGS_ORG, normalize

REVIEW_ORG = SONGS_ORG.with_name("rescue-review.org")
SEARCH_RESULTS = 6

BAD_VIDEO_PATTERN = re.compile(
    r"live|cover|翻唱|伴奏|karaoke|ktv|dj|remix|1小时|一小时|合集|串烧|教学|instrumental|piano|吉他|reaction|片段",
    re.IGNORECASE,
)
LIVE_SHOW_PATTERN = re.compile(r"现场|演唱会|跨年|晚会|节目|新歌声|好声音|纯享|clip|封神|修复|concert", re.IGNORECASE)
OFFICIAL_CHANNEL_PATTERN = re.compile(r"official|官方|唱片|records|music|vevo|音乐", re.IGNORECASE)
MUSIC_VIDEO_PATTERN = re.compile(r"\bmv\b|music video|official video|官方", re.IGNORECASE)


def ticked_songs() -> list[tuple[str, str]]:
    """Return (artist, title) of every ticked checkbox in rescue.org, with hashtags stripped from titles."""
    songs = []
    artist = None
    for line in RESCUE_ORG.read_text().splitlines():
        if heading := re.match(r"^\* (.+?)(?: \[\d*/\d*\])?$", line):
            artist = heading.group(1)
        elif item := re.match(r"^- \[X\] (.+)$", line):
            songs.append((artist, re.sub(r"\s*#\S+", "", item.group(1)).strip()))
    return songs


def search(artist: str, title: str) -> list[dict]:
    """Return YouTube search results for the song as dicts with id, title, duration (seconds) and channel."""
    output = subprocess.run(
        ["yt-dlp", f"ytsearch{SEARCH_RESULTS}:{title} {artist}", "--flat-playlist",
         "--print", "%(id)s\t%(title)s\t%(duration)s\t%(channel)s"],
        capture_output=True, text=True,
    ).stdout
    results = []
    for line in output.splitlines():
        parts = line.split("\t")
        if len(parts) == 4:
            video_id, video_title, duration, channel = parts
            results.append({"id": video_id, "title": video_title, "channel": channel,
                            "duration": int(float(duration)) if duration not in ("NA", "") else 0})
    return results


def score(video: dict, artist: str, title: str) -> int:
    """Rank how likely `video` is the original recording of the song; higher is better."""
    name = normalize(video["title"])
    points = 0
    points += 4 if normalize(title) in name else 0
    points += 2 if normalize(artist) in name or normalize(artist) in normalize(video["channel"]) else 0
    points += 1 if OFFICIAL_CHANNEL_PATTERN.search(video["channel"]) else 0
    points += 2 if MUSIC_VIDEO_PATTERN.search(video["title"]) else 0
    points -= 5 if BAD_VIDEO_PATTERN.search(video["title"]) else 0
    points -= 4 if LIVE_SHOW_PATTERN.search(video["title"]) else 0
    points -= 3 if not 120 <= video["duration"] <= 480 else 0
    return points


def pick(song: tuple[str, str]) -> tuple[str, str, dict | None]:
    """Return (artist, title, best video or None) for one song."""
    artist, title = song
    videos = search(artist, title)
    best = max(videos, key=lambda v: score(v, artist, title), default=None)
    return artist, title, best


def write_review():
    """Write picks for ticked songs to rescue-review.org; if it exists, append only songs not yet in it."""
    songs = ticked_songs()
    known = {normalize(song.heading) for section in load(SONGS_ORG).children for song in section.children}
    reviewed = set()
    if REVIEW_ORG.exists():
        reviewed = {normalize(song.heading) for section in load(REVIEW_ORG).children for song in section.children}
    todo = [s for s in songs if normalize(s[1]) not in known | reviewed]
    print(f"{len(songs)} ticked, {len(songs) - len(todo)} already in songs.org or {REVIEW_ORG.name}, searching {len(todo)}")
    if not todo:
        return
    with ThreadPoolExecutor(max_workers=4) as pool:
        picks = list(pool.map(pick, todo))

    lines = [] if REVIEW_ORG.exists() else [
        "#+title: Rescue songs to review",
        "Best YouTube match per ticked song (generated by rescue_pick.py).",
        "Fix wrong URLs, delete unwanted entries, then run: python rescue_pick.py --apply",
        "",
    ]
    by_artist: dict[str, list] = {}
    for artist, title, video in picks:
        by_artist.setdefault(artist, []).append((title, video))
    for artist, entries in by_artist.items():
        lines.append(f"* {artist}")
        for title, video in entries:
            lines.append(f"** {title}")
            if video:
                lines.append(f"https://www.youtube.com/watch?v={video['id']}")
                lines.append(f"# {video['title']} | {video['channel']} | {video['duration'] // 60}:{video['duration'] % 60:02d}")
            else:
                lines.append("# 没找到，请手动填链接")
    with REVIEW_ORG.open("a") as review:
        review.write("\n".join(lines) + "\n")
    print(f"added {len(picks)} songs to {REVIEW_ORG}; {sum(v is None for _, _, v in picks)} without a match")


def apply_review():
    """Append reviewed entries to songs.org under their artist section, creating sections as needed."""
    entries = []
    for section in load(REVIEW_ORG).children:
        for song in section.children:
            url = next((l.strip() for l in song.body.splitlines() if l.strip().startswith("http")), None)
            if url:
                entries.append((section.heading, song.heading, url))

    text = SONGS_ORG.read_text()
    known = {normalize(song.heading) for section in load(SONGS_ORG).children for song in section.children}
    added = 0
    for artist, title, url in entries:
        if normalize(title) in known:
            continue
        entry = f"** {title}\n{url}\n"
        heading = re.search(rf"^\* (?:[A-Z]+ )?{re.escape(artist)}[ \t]*$", text, flags=re.M)
        if heading:
            next_section = re.search(r"^\* ", text[heading.end():], flags=re.M)
            at = heading.end() + next_section.start() if next_section else len(text)
            prefix = "" if text[:at].endswith("\n") else "\n"
            text = text[:at] + prefix + entry + text[at:]
        else:
            text = text.rstrip("\n") + f"\n* {artist}\n" + entry
        known.add(normalize(title))
        added += 1
    SONGS_ORG.write_text(text)
    print(f"added {added} songs to {SONGS_ORG}; now run: python main.py")


if __name__ == "__main__":
    apply_review() if "--apply" in sys.argv else write_review()
